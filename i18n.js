function applyLanguage(lang) {
  const activeLang = I18N[lang] ? lang : "id";
  document.body.setAttribute("data-lang", activeLang);
  const dict = I18N[activeLang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  document.querySelectorAll(".lang-btn").forEach((b) => {
    b.classList.toggle("is-active", b.dataset.langBtn === activeLang);
  });

  localStorage.setItem("banten_preferred_lang", activeLang);
  document.documentElement.setAttribute("lang", activeLang);
}

// Auto init language from storage
document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("banten_preferred_lang") || "id";
  applyLanguage(savedLang);
});
